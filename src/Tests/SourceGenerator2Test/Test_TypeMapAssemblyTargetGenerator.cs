using System.IO;
using System.Linq;
using Basic.Reference.Assemblies;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Emit;
using Microsoft.CodeAnalysis.Diagnostics;
using WindowsRuntime.SourceGenerator.Tests.Helpers;

namespace WindowsRuntime.SourceGenerator.Tests;

[TestClass]
public sealed class Test_TypeMapAssemblyTargetGenerator
{
    [TestMethod]
    [DataRow("TypeMapAssemblyTarget.PrivateProjections.g.cs", "ReferenceProjection")]
    [DataRow("TypeMapAssemblyTarget.Sdk.g.cs", "WinRT.Sdk.Projection")]
    [DataRow("TypeMapAssemblyTarget.Sdk.Xaml.g.cs", "WinRT.Sdk.Xaml.Projection")]
    [DataRow("TypeMapAssemblyTarget.ExternalProjections.g.cs", "WinRT.Projection")]
    [DataRow("TypeMapAssemblyTarget.Component.g.cs", "WinRT.Component")]
    public void GeneratedAttributes_HaveBlankLineAfterHeader(string filename, string assemblyName)
    {
        CSharpCompilation referenceCompilation = CSharpCompilation.Create(
            "ReferenceProjection",
            syntaxTrees: [CSharpSyntaxTree.ParseText("""
                [assembly: WindowsRuntime.InteropServices.WindowsRuntimeReferenceAssembly]
                [assembly: WindowsRuntime.InteropServices.WindowsRuntimeComponentAssembly]
                """)],
            references:
            [
                .. Net100.References.All,
                MetadataReference.CreateFromFile(typeof(WindowsRuntimeObject).Assembly.Location)
            ],
            options: new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        using MemoryStream stream = new();

        EmitResult emitResult = referenceCompilation.Emit(stream);

        Assert.IsTrue(emitResult.Success, string.Join("\n", emitResult.Diagnostics));

        CSharpCompilation compilation = CSharpCompilation.Create(
            "TestApp",
            references: referenceCompilation.References.Append(MetadataReference.CreateFromImage(stream.ToArray())),
            options: new CSharpCompilationOptions(OutputKind.ConsoleApplication));

        GeneratorDriver driver = CSharpGeneratorDriver.Create(
            generators: [new TypeMapAssemblyTargetGenerator().AsSourceGenerator()],
            optionsProvider: new XamlOptionsProvider());
        GeneratorDriverRunResult result = driver.RunGenerators(compilation).GetRunResult();

        Assert.IsEmpty(result.Diagnostics);

        string source = result.GeneratedTrees.Single(tree => Path.GetFileName(tree.FilePath) == filename).ToString().Replace("\r\n", "\n");

        StringAssert.StartsWith(source, "// <auto-generated/>\n#pragma warning disable\n\n[assembly:");
        Assert.Contains(
            $$"""[assembly: global::System.Runtime.InteropServices.TypeMapAssemblyTarget<global::WindowsRuntime.InteropServices.WindowsRuntimeIidTypeMapGroup>("{{assemblyName}}")]""",
            source);

        if (filename == "TypeMapAssemblyTarget.Sdk.g.cs")
        {
            Assert.Contains(
                """[assembly: global::System.Runtime.InteropServices.TypeMapAssemblyTarget<global::WindowsRuntime.InteropServices.WindowsRuntimeIidTypeMapGroup>("WinRT.Runtime")]""",
                source);
        }
    }

    [TestMethod]
    public void Component_RegistersTheExternalIidMap()
    {
        string source = CSharpGeneratorTest<TypeMapAssemblyTargetGenerator>.GetGeneratedSource(
            "", "TypeMapAssemblyTarget.Sdk.g.cs", isCsWinRTComponent: true);
        Assert.Contains(
            """[assembly: global::System.Runtime.InteropServices.TypeMapAssemblyTarget<global::WindowsRuntime.InteropServices.WindowsRuntimeIidTypeMapGroup>("WinRT.Interop")]""",
            source);
        Assert.Contains(
            """[assembly: global::System.Runtime.InteropServices.TypeMapAssemblyTarget<global::WindowsRuntime.InteropServices.WindowsRuntimeIidTypeMapGroup>("WinRT.Runtime")]""",
            source);
    }

    private sealed class XamlOptionsProvider : AnalyzerConfigOptionsProvider
    {
        public override AnalyzerConfigOptions GlobalOptions { get; } = new XamlOptions();

        public override AnalyzerConfigOptions GetOptions(SyntaxTree tree) => GlobalOptions;

        public override AnalyzerConfigOptions GetOptions(AdditionalText textFile) => GlobalOptions;

        private sealed class XamlOptions : AnalyzerConfigOptions
        {
            public override bool TryGetValue(string key, out string value)
            {
                value = "true";
                return key == "build_property.CsWinRTUseWindowsUIXamlProjections";
            }
        }
    }
}
