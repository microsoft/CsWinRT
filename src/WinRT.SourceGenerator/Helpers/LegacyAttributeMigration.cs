using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;

// This file is also compiled for 'netstandard2.0', where range syntax is unavailable
#pragma warning disable IDE0057

namespace WindowsRuntime.Migration;

/// <summary>
/// Shares legacy attribute identity and migration contracts between analysis and code fixes.
/// </summary>
internal static class LegacyAttributeMigration
{
    /// <summary>The diagnostic for a supported attribute migration.</summary>
    public const string DiagnosticId = "CSWINRT2051";

    /// <summary>The diagnostic for an attribute requiring contract review.</summary>
    public const string ReviewDiagnosticId = "CSWINRT2052";

    /// <summary>The actionable mapping suggestion for a legacy array parameter.</summary>
    public const string ArrayDiagnosticId = "CSWINRT2053";

    /// <summary>Gets the expected span mapping for a recognized single-dimensional array parameter.</summary>
    /// <param name="attribute">The attribute application.</param>
    /// <param name="model">The semantic model.</param>
    /// <param name="token">The cancellation token.</param>
    /// <param name="spanName">The framework span metadata name.</param>
    /// <returns>Whether the attribute establishes an array-to-span mapping.</returns>
    public static bool TryGetArraySpanName(
        AttributeSyntax attribute, SemanticModel model, CancellationToken token, out string? spanName)
    {
        spanName = GetLegacyName(attribute, model, token) switch
        {
            "System.Runtime.InteropServices.WindowsRuntime.ReadOnlyArrayAttribute" => "System.ReadOnlySpan`1",
            "System.Runtime.InteropServices.WindowsRuntime.WriteOnlyArrayAttribute" => "System.Span`1",
            _ => null
        };

        return spanName is not null && attribute.Parent?.Parent is ParameterSyntax parameter &&
               model.GetDeclaredSymbol(parameter, token)?.Type is IArrayTypeSymbol
               { IsSZArray: true, ElementType.TypeKind: not (TypeKind.Array or TypeKind.Pointer or TypeKind.FunctionPointer) };
    }

    /// <summary>Identifies a CsWinRT 3.0 source compilation.</summary>
    /// <param name="tree">The source tree.</param>
    /// <returns>Whether the 3.0 selection symbol is enabled.</returns>
    public static bool IsVersion3(SyntaxTree tree)
    {
        return tree.Options is CSharpParseOptions options &&
               options.PreprocessorSymbolNames.Contains("CSWINRT3_0");
    }

    /// <summary>Excludes generated source, including explicit editor configuration.</summary>
    /// <param name="tree">The source tree.</param>
    /// <param name="options">The analyzer configuration.</param>
    /// <param name="token">The cancellation token.</param>
    /// <returns>Whether the source is generated.</returns>
    public static bool IsGenerated(SyntaxTree tree, AnalyzerConfigOptionsProvider options, CancellationToken token)
    {
        string name = Path.GetFileName(tree.FilePath);
        string header = tree.GetRoot(token).GetLeadingTrivia().ToFullString();

        return name.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase) ||
               name.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) ||
               name.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase) ||
               name.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase) ||
               name.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase) ||
               header.IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0 ||
               header.IndexOf("<autogenerated", StringComparison.OrdinalIgnoreCase) >= 0 ||
               (options.GetOptions(tree).TryGetValue("generated_code", out string? value) &&
                string.Equals(value, "true", StringComparison.OrdinalIgnoreCase));
    }

    /// <summary>Filters ordinary attribute names before semantic analysis.</summary>
    /// <param name="name">The unqualified attribute spelling.</param>
    /// <returns>Whether the spelling can name an attribute in the catalog.</returns>
    public static bool IsCandidateName(string name)
    {
        return NormalizeKnownName("WinRT." + name) is not null ||
               NormalizeKnownName("WinRT.Interop." + name) is not null ||
               NormalizeKnownName("System.Runtime.InteropServices.WindowsRuntime." + name) is not null;
    }

    /// <summary>Checks directives inside a replacement span rather than its surrounding trivia.</summary>
    /// <param name="node">The replaced syntax.</param>
    /// <returns>Whether moving the syntax would move an interior directive.</returns>
    public static bool HasInteriorDirectives(SyntaxNode node)
    {
        return node.ContainsDirectives && node.DescendantTrivia(descendIntoTrivia: true)
            .Any(trivia => node.Span.Contains(trivia.Span) && trivia.GetStructure() is DirectiveTriviaSyntax);
    }

    /// <summary>Classifies a verified legacy attribute without inventing equivalent contracts.</summary>
    /// <param name="attribute">The attribute application.</param>
    /// <param name="model">The source semantic model.</param>
    /// <param name="token">The cancellation token.</param>
    /// <param name="name">The legacy metadata name.</param>
    /// <param name="replacement">The replacement metadata name, or null for removal.</param>
    /// <param name="review">Whether the application requires manual contract review.</param>
    /// <returns>Whether the application is a recognized legacy attribute.</returns>
    public static bool TryGetMigration(
        AttributeSyntax attribute,
        SemanticModel model,
        CancellationToken token,
        out string? name,
        out string? replacement,
        out bool review)
    {
        name = GetLegacyName(attribute, model, token);
        replacement = null;
        review = false;

        switch (name)
        {
            case "WinRT.DynamicWindowsRuntimeCastAttribute":
            case "WinRT.GeneratedWinRTExposedTypeAttribute":
                break;
            case "WinRT.GeneratedBindableCustomPropertyAttribute":
                replacement = "WindowsRuntime.Xaml.GeneratedCustomPropertyProviderAttribute";
                break;
            case "WinRT.WinRTRuntimeClassNameAttribute":
                replacement = "WindowsRuntime.WindowsRuntimeClassNameAttribute";
                break;
            case "WinRT.GeneratedWinRTExposedExternalTypeAttribute":
                if (GetTypeArgument(attribute, model, token) is not INamedTypeSymbol { TypeKind: TypeKind.Class or TypeKind.Struct } externalType)
                {
                    review = true;
                }
                else if (IsProjectedClass(externalType))
                {
                    review = externalType.IsAbstract || externalType.IsStatic || externalType.IsGenericType;
                    replacement = review ? null : "WindowsRuntime.InteropServices.WindowsRuntimeNativeExposedTypeAttribute";
                }
                break;
            case "WinRT.WinRTExposedTypeAttribute":
                // Custom details can supply arbitrary vtables or block all marshalling, neither of which a rename preserves
                review = attribute.ArgumentList?.Arguments.Count > 0;
                break;
            case "WinRT.ProjectedRuntimeClassAttribute":
            case "WinRT.ObjectReferenceWrapperAttribute":
                review = true;
                break;
            case "System.Runtime.InteropServices.WindowsRuntime.ReadOnlyArrayAttribute":
            case "System.Runtime.InteropServices.WindowsRuntime.WriteOnlyArrayAttribute":
                string spanName = name.EndsWith(".ReadOnlyArrayAttribute", StringComparison.Ordinal)
                    ? "System.ReadOnlySpan<T>"
                    : "System.Span<T>";
                review = attribute.Parent?.Parent is not ParameterSyntax parameter ||
                         model.GetDeclaredSymbol(parameter, token)?.Type.OriginalDefinition.ToDisplayString() != spanName;
                break;
            case "WinRT.WindowsRuntimeTypeAttribute":
            case "WinRT.WindowsRuntimeHelperTypeAttribute":
            case "WinRT.WinRTImplementationTypeRcwFactoryAttribute":
            case "WinRT.WinRTAssemblyExportsTypeAttribute":
            case "WinRT.Interop.WuxMuxProjectedTypeAttribute":
                review = true;
                break;
            default:
                return false;
        }

        if (replacement is not null &&
            model.Compilation.GetTypeByMetadataName(replacement) is not { DeclaredAccessibility: Accessibility.Public, ContainingAssembly.Identity.Name: "WinRT.Runtime" })
        {
            review = true;
        }

        return true;
    }

    /// <summary>Resolves a bound legacy type or conservatively recovers its missing name after retargeting.</summary>
    /// <param name="attribute">The attribute application.</param>
    /// <param name="model">The source semantic model.</param>
    /// <param name="token">The cancellation token.</param>
    /// <returns>The known metadata name, or null for unrelated or ambiguous attributes.</returns>
    private static string? GetLegacyName(AttributeSyntax attribute, SemanticModel model, CancellationToken token)
    {
        SymbolInfo info = model.GetSymbolInfo(attribute, token);

        if (info.Symbol is IMethodSymbol constructor)
        {
            INamedTypeSymbol type = constructor.ContainingType;
            string name = type.ToDisplayString();
            bool runtime = type.ContainingAssembly.Identity is { Name: "WinRT.Runtime", Version.Major: 2 };
            bool polyfill = name == "WinRT.DynamicWindowsRuntimeCastAttribute" &&
                            type.GetAttributes().Any(static item =>
                                item.AttributeClass?.ToDisplayString() == "System.Diagnostics.ConditionalAttribute" &&
                                item.ConstructorArguments.Length == 1 &&
                                item.ConstructorArguments[0].Value is "CSWINRT2_0_POLYFILL_ATTRIBUTES") &&
                            type.GetAttributes().Any(static item =>
                                item.AttributeClass?.ToDisplayString() == "Microsoft.CodeAnalysis.EmbeddedAttribute") &&
                            type.DeclaringSyntaxReferences.Any(reference =>
                                reference.SyntaxTree.GetRoot(token).GetLeadingTrivia().ToFullString().Contains("<auto-generated"));

            for (INamedTypeSymbol? current = type.BaseType; current is not null; current = current.BaseType)
            {
                if (current.ToDisplayString() == "WinRT.WinRTImplementationTypeRcwFactoryAttribute" &&
                    current.ContainingAssembly.Identity is { Name: "WinRT.Runtime", Version.Major: 2 })
                {
                    return "WinRT.WinRTImplementationTypeRcwFactoryAttribute";
                }
            }

            return (runtime || polyfill) && IsKnownName(name) ? name : null;
        }

        if (!info.CandidateSymbols.IsEmpty ||
            model.GetSymbolInfo(attribute.Name, token).Symbol is INamedTypeSymbol { TypeKind: not TypeKind.Error })
        {
            return null;
        }

        string spelling = attribute.Name.ToString().Replace("global::", "").Replace("::", ".");
        string first = spelling.Split('.')[0];
        UsingDirectiveSyntax[] imports = [.. GetUsings(attribute, model, token)];
        UsingDirectiveSyntax? alias = imports.FirstOrDefault(item => item.Alias?.Name.Identifier.ValueText == first);

        if (alias?.Name is { } aliasName)
        {
            spelling = aliasName.ToString().Replace("global::", "").Replace("::", ".") + spelling.Substring(first.Length);
        }

        if (spelling.Contains("."))
        {
            return NormalizeKnownName(spelling);
        }

        if (!model.LookupNamespacesAndTypes(attribute.SpanStart, name: first).IsEmpty ||
            !model.LookupNamespacesAndTypes(attribute.SpanStart, name: first + "Attribute").IsEmpty)
        {
            return null;
        }

        string[] candidates = [.. imports.Where(static item => item.Alias is null && !item.StaticKeyword.IsKind(SyntaxKind.StaticKeyword))
            .Select(item => NormalizeKnownName(item.Name + "." + spelling))
            .OfType<string>().Distinct()];

        return candidates.Length == 1 ? candidates[0] : null;
    }

    /// <summary>Enumerates imports visible at an attribute, including global imports in other trees.</summary>
    /// <param name="attribute">The attribute application.</param>
    /// <param name="model">The source semantic model.</param>
    /// <param name="token">The cancellation token.</param>
    /// <returns>The applicable imports.</returns>
    private static IEnumerable<UsingDirectiveSyntax> GetUsings(AttributeSyntax attribute, SemanticModel model, CancellationToken token)
    {
        foreach (SyntaxNode scope in attribute.Ancestors())
        {
            IEnumerable<UsingDirectiveSyntax> imports = scope switch
            {
                CompilationUnitSyntax unit => unit.Usings,
                BaseNamespaceDeclarationSyntax declaration => declaration.Usings,
                _ => []
            };

            foreach (UsingDirectiveSyntax import in imports)
            {
                yield return import;
            }
        }

        foreach (SyntaxTree tree in model.Compilation.SyntaxTrees)
        {
            if (tree == attribute.SyntaxTree)
            {
                continue;
            }

            foreach (UsingDirectiveSyntax import in ((CompilationUnitSyntax)tree.GetRoot(token)).Usings)
            {
                if (import.GlobalKeyword.IsKind(SyntaxKind.GlobalKeyword))
                {
                    yield return import;
                }
            }
        }
    }

    /// <summary>Normalizes an optional attribute suffix against the exact legacy catalog.</summary>
    /// <param name="name">The qualified spelling.</param>
    /// <returns>The metadata name, or null.</returns>
    private static string? NormalizeKnownName(string name)
    {
        return IsKnownName(name) ? name : IsKnownName(name + "Attribute") ? name + "Attribute" : null;
    }

    /// <summary>Checks the legacy catalog without namespace-prefix or substring matching.</summary>
    /// <param name="name">The metadata name.</param>
    /// <returns>Whether the name is in the catalog.</returns>
    private static bool IsKnownName(string name)
    {
        return name is "WinRT.DynamicWindowsRuntimeCastAttribute" or
            "WinRT.GeneratedWinRTExposedTypeAttribute" or "WinRT.GeneratedWinRTExposedExternalTypeAttribute" or
            "WinRT.GeneratedBindableCustomPropertyAttribute" or "WinRT.WinRTRuntimeClassNameAttribute" or
            "WinRT.WinRTExposedTypeAttribute" or "WinRT.ProjectedRuntimeClassAttribute" or
            "WinRT.ObjectReferenceWrapperAttribute" or "WinRT.WindowsRuntimeTypeAttribute" or
            "WinRT.WindowsRuntimeHelperTypeAttribute" or "WinRT.WinRTImplementationTypeRcwFactoryAttribute" or
            "WinRT.WinRTAssemblyExportsTypeAttribute" or "WinRT.Interop.WuxMuxProjectedTypeAttribute" or
            "System.Runtime.InteropServices.WindowsRuntime.ReadOnlyArrayAttribute" or
            "System.Runtime.InteropServices.WindowsRuntime.WriteOnlyArrayAttribute";
    }

    /// <summary>Gets a single typeof argument without inferring an unresolved type.</summary>
    /// <param name="attribute">The attribute application.</param>
    /// <param name="model">The semantic model.</param>
    /// <param name="token">The cancellation token.</param>
    /// <returns>The argument type, or null.</returns>
    private static ITypeSymbol? GetTypeArgument(AttributeSyntax attribute, SemanticModel model, CancellationToken token)
    {
        return attribute.ArgumentList?.Arguments.Count == 1 &&
               attribute.ArgumentList.Arguments[0].Expression is TypeOfExpressionSyntax expression
            ? model.GetTypeInfo(expression.Type, token).Type
            : null;
    }

    /// <summary>Checks the base chain used by new runtime-class projections.</summary>
    /// <param name="type">The class type.</param>
    /// <returns>Whether it derives from the 3.0 runtime object.</returns>
    private static bool DerivesFromRuntimeObject(INamedTypeSymbol type)
    {
        for (INamedTypeSymbol? current = type.BaseType; current is not null; current = current.BaseType)
        {
            if (current.ToDisplayString() == "WindowsRuntime.WindowsRuntimeObject" &&
                current.ContainingAssembly.Identity.Name == "WinRT.Runtime")
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>Recognizes projected classes through the reference-assembly marker or runtime base.</summary>
    /// <param name="type">The target type.</param>
    /// <returns>Whether it is a projected class.</returns>
    private static bool IsProjectedClass(INamedTypeSymbol type)
    {
        return type.TypeKind == TypeKind.Class &&
               (DerivesFromRuntimeObject(type) || type.ContainingAssembly.GetAttributes().Any(static attribute =>
                   attribute.AttributeClass?.ToDisplayString() == "WindowsRuntime.InteropServices.WindowsRuntimeReferenceAssemblyAttribute" &&
                   attribute.AttributeClass.ContainingAssembly.Identity.Name == "WinRT.Runtime"));
    }
}
