using System;
using System.Linq;
using Microsoft.CodeAnalysis;
using WindowsRuntime.SourceGenerator.Models;

namespace WindowsRuntime.SourceGenerator;

/// <inheritdoc cref="GetIidInterceptorGenerator"/>
public partial class GetIidInterceptorGenerator
{
    /// <summary>
    /// Emission methods for <see cref="GetIidInterceptorGenerator"/>.
    /// </summary>
    private static class Emit
    {
        /// <summary>
        /// Emits one interceptor with RVA-backed IID data per distinct IID.
        /// </summary>
        /// <param name="context">The output context.</param>
        /// <param name="items">The interceptable calls.</param>
        public static void WriteInterceptors(SourceProductionContext context, EquatableArray<GetIidInterceptorInfo> items)
        {
            if (items.IsEmpty)
            {
                return;
            }

            IndentedTextWriter writer = new(literalLength: 2048, formattedCount: 0);
            writer.WriteLine("""
                // <auto-generated/>
                #pragma warning disable

                namespace System.Runtime.CompilerServices
                {
                    [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]
                    file sealed class InterceptsLocationAttribute(int version, string data) : global::System.Attribute;
                }

                namespace WindowsRuntime.Generated
                """, isMultiline: true);

            using (writer.WriteBlock())
            {
                writer.WriteLine("file static class GetIidInterceptors");

                using (writer.WriteBlock())
                {
                    foreach (IGrouping<Guid, GetIidInterceptorInfo> group in items.GroupBy(static item => item.Iid).OrderBy(static group => group.Key))
                    {
                        context.CancellationToken.ThrowIfCancellationRequested();
                        string name = $"Iid_{group.Key:N}";
                        string bytes = string.Join(", ", group.Key.ToByteArray().Select(static value => $"0x{value:X2}"));

                        foreach (GetIidInterceptorInfo item in group)
                        {
                            writer.WriteLine($"""[global::System.Runtime.CompilerServices.InterceptsLocationAttribute({item.Version}, "{item.Data}")]""");
                        }

                        writer.WriteLine($$"""
                            [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]
                            public static global::System.Guid Get_{{name}}()
                            {
                                global::System.ReadOnlySpan<byte> data = [{{bytes}}];

                                return global::System.Runtime.CompilerServices.Unsafe.As<byte, global::System.Guid>(
                                    ref global::System.Runtime.InteropServices.MemoryMarshal.GetReference(data));
                            }

                            """, isMultiline: true);
                    }
                }
            }

            context.AddSource("GetIidInterceptors.g.cs", writer.ToStringAndClear());
        }
    }
}
