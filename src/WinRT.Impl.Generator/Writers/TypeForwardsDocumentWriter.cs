using System.Collections.Generic;
using System.Text;
using AsmResolver.DotNet;

namespace WindowsRuntime.ImplGenerator.Writers;

/// <summary>
/// Writes the generated document describing the type forwards in a forwarder assembly.
/// </summary>
/// <remarks>
/// This document is what the synthesized portable PDB embeds as the source of the forwarder assembly. The
/// forwarder has no source on disk, so this is written to be an accurate, human readable description of
/// everything the assembly contains: the C# that would produce exactly these type forwards.
/// </remarks>
internal static class TypeForwardsDocumentWriter
{
    /// <summary>
    /// Writes the document describing the type forwards of a forwarder assembly.
    /// </summary>
    /// <param name="implModule">The forwarder module the document describes.</param>
    /// <returns>The text of the generated document.</returns>
    public static string Write(ModuleDefinition implModule)
    {
        StringBuilder builder = new();

        _ = builder.Append(
            """
            // <auto-generated/>
            //
            // This document is generated by 'cswinrtimplgen', and describes the assembly it is embedded in.
            //
            // That assembly is a forwarder: it stands in for the reference projection it was built from, and
            // contains no executable code of its own. It only redirects the projected Windows Runtime types to
            // the projection assembly that CsWinRT generates when the consuming application is built, which is
            // what lets an application pick up a new CsWinRT version without every library it uses shipping an
            // update as well.
            //
            // The type forwards below are the entire contents of the assembly.
            """.ReplaceLineEndings("\n"));

        // Separate the header from the type forwards with a blank line. This is done explicitly, as a raw
        // string literal drops the newline before its closing delimiter (so trailing blank lines there would
        // have to be doubled up to survive), and 'AppendLine' would emit the platform newline instead of '\n'.
        _ = builder.Append("\n\n");

        foreach (ExportedType exportedType in implModule.ExportedTypes)
        {
            _ = builder
                .Append("[assembly: global::System.Runtime.CompilerServices.TypeForwardedTo(typeof(global::")
                .Append(exportedType.Namespace)
                .Append('.')
                .Append(exportedType.Name)
                .Append("))]")
                .Append('\n');
        }

        return builder.ToString();
    }

    /// <summary>
    /// Gets the names of the assemblies a forwarder module references.
    /// </summary>
    /// <param name="implModule">The forwarder module to inspect.</param>
    /// <returns>The referenced assembly file names.</returns>
    public static IReadOnlyList<MetadataReferenceInfo> GetReferences(ModuleDefinition implModule)
    {
        List<MetadataReferenceInfo> references = [];

        foreach (AssemblyReference assemblyReference in implModule.AssemblyReferences)
        {
            references.Add(new MetadataReferenceInfo($"{assemblyReference.Name}.dll"));
        }

        return references;
    }
}
